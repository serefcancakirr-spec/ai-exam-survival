export const ydtDeckId = (key: YdtDeckKey) => `ydt-words-${key}`;

/** Default deck name in the language in use. */
export function ydtDeckName(key: YdtDeckKey, lang: 'tr' | 'en') {
  return lang === 'tr' ? `YDT – ${YDT_DECK_NAMES[key].tr}` : `YDT – ${YDT_DECK_NAMES[key].en}`;
}

/** Turkish locative ending after a number: 9’unda, 6’sında … */
const LOCATIVE: Record<number, string> = { 1: 'inde', 2: 'sinde', 3: 'ünde', 4: 'ünde', 5: 'inde', 6: 'sında', 7: 'sinde', 8: 'inde', 9: 'unda' };

/** The back-of-card note: synonym, in how many booklets the word appears and when it was a question option (real counts). */
export function ydtWordNote([, , , years, synonym, tested]: YdtWord, lang: 'tr' | 'en') {
  const parts: string[] = [];
  if (synonym) parts.push(lang === 'tr' ? `Eş anlamlı: ${synonym}` : `Synonym: ${synonym}`);
  parts.push(
    lang === 'tr'
      ? `2018–2026 arasındaki ${YDT_BOOKLETS} YDT kitapçığının ${years}’${LOCATIVE[years]} geçti`
      : `Appears in ${years} of the ${YDT_BOOKLETS} YDT booklets (2018–2026)`,
  );
  if (tested.length > 0) {
    parts.push(lang === 'tr' ? `Kelime / dil bilgisi sorularında seçenek oldu: ${tested.join(', ')}` : `An option in vocabulary / grammar questions: ${tested.join(', ')}`);
  }
  return `${parts.join('. ')}.`;
}

/** A new YDT word deck and its cards, named in the language in use (grade 12, English). */
export function createYdtDeck(key: YdtDeckKey, lang: 'tr' | 'en', grade: FlashcardGrade, name: string, now = new Date().toISOString()) {
  const id = ydtDeckId(key);
  const deck: FlashcardDeck = {
    id,
    name,
    grade,
    subject: 'English',
    topic: `YDT · ${YDT_DECK_NAMES[key][lang]}`,
    starter: false,
    createdAt: now,
  };
  const cards: Flashcard[] = YDT_WORDS[key].map((word, index) => ({
    id: `${id}-${String(index + 1).padStart(2, '0')}`,
    deckId: id,
    front: `${word[0]} — “${word[2]}”`,
    answer: word[1],
    explanation: ydtWordNote(word, lang),
  }));
  return { deck, cards };
}
