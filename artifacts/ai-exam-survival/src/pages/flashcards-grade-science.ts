export const scienceGradeDeckId = (grade: ScienceGrade, subject: ScienceSubject) => `${subject.toLowerCase()}-grade-${grade}`;

/** Deck name, e.g. "9. sınıf Fizik – anahtar kavramlar" / "Physics 9 – key concepts". */
export function scienceGradeDeckName(grade: ScienceGrade, subject: ScienceSubject, lang: 'tr' | 'en') {
  return lang === 'tr' ? `${grade}. sınıf ${PROGRAM_NAMES[subject].tr} – anahtar kavramlar` : `${PROGRAM_NAMES[subject].en} ${grade} – key concepts`;
}

/** Card explanation: where the concept is in the MEB program. */
export function scienceConceptNote(grade: ScienceGrade, subject: ScienceSubject, concept: GradeConcept, lang: 'tr' | 'en') {
  const deck = SCIENCE_GRADE_DECKS[grade][subject];
  const [, , unit, fromContent] = concept;
  const title = deck.units[unit];
  if (lang === 'tr') {
    return `MEB ${PROGRAM_NAMES[subject].tr} öğretim programı · ${grade}. sınıf · ${unit}. ${deck.unitWord}: ${title} (${fromContent ? 'programın içeriğinden' : 'anahtar kavram'}).`;
  }
  return `MEB ${PROGRAM_NAMES[subject].en} curriculum · Grade ${grade} · ${deck.unitWord === 'ünite' ? 'Unit' : 'Theme'} ${unit}: ${title} (${fromContent ? 'from the program content' : 'key concept'}).`;
}

export function createScienceGradeDeck(
  grade: ScienceGrade,
  subject: ScienceSubject,
  lang: 'tr' | 'en',
  name: string,
  now = new Date().toISOString(),
) {
  const id = scienceGradeDeckId(grade, subject);
  const deck: FlashcardDeck = {
    id,
    name,
    grade: grade as FlashcardGrade,
    subject,
    topic: lang === 'tr' ? 'MEB · Anahtar kavramlar' : 'MEB · Key concepts',
    starter: false,
    createdAt: now,
  };
  const cards: Flashcard[] = SCIENCE_GRADE_DECKS[grade][subject].concepts.map((concept, index) => ({
    id: `${id}-${String(index + 1).padStart(2, '0')}`,
    deckId: id,
    front: concept[0],
    answer: concept[1],
    explanation: scienceConceptNote(grade, subject, concept, lang),
  }));
  return { deck, cards };
}
