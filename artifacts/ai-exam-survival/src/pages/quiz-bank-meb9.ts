// In each question below the FIRST option is the correct one; the bank moves it to a different letter.
import type { QuizDifficulty, QuizSubject } from './quiz-question-bank';

export type Meb9Seed = {
  /** MEB learning outcome code, e.g. "MAT.9.1.1". */
  outcome: string;
  /** MEB theme name (shown as the quiz topic). */
  theme: string;
  difficulty: QuizDifficulty;
  prompt: string;
  /** The first option is the correct answer. */
  options: [string, string, string, string];
  explanation: string;
};

/** Theme of each learning-outcome group ("9.1" = first theme), from the official frame plans. */
export const MEB9_THEMES: Record<string, Record<string, string>> = {
  MAT: {
    '9.1': 'Sayılar',
    '9.2': 'Nicelikler ve Değişimler',
    '9.3': 'Geometrik Şekiller',
    '9.4': 'Eşlik ve Benzerlik',
    '9.5': 'Algoritma ve Bilişim',
    '9.6': 'İstatistiksel Araştırma Süreci',
    '9.7': 'Veriden Olasılığa',
  },
  FİZ: {
    '9.1': 'Fizik Bilimi ve Kariyer Keşfi',
    '9.2': 'Kuvvet ve Hareket',
    '9.3': 'Akışkanlar',
    '9.4': 'Enerji',
  },
  KİM: {
    '9.1': 'Etkileşim',
    '9.2': 'Çeşitlilik',
    '9.3': 'Sürdürülebilirlik',
  },
  BİY: {
    '9.1': 'Yaşam',
    '9.2': 'Organizasyon',
  },
};

function q(
  outcome: string,
  difficulty: QuizDifficulty,
  prompt: string,
  options: [string, string, string, string],
  explanation: string,
): Meb9Seed {
  const [prefix, grade, unit] = outcome.split('.');
  const theme = MEB9_THEMES[prefix]?.[`${grade}.${unit}`];
  if (!theme) throw new Error(`Unknown MEB outcome ${outcome}`);
  return { outcome, theme, difficulty, prompt, options, explanation };
}

