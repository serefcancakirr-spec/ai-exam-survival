/** Subjects that have a deck in this grade (Felsefe only in grades 10 and 11). */
export const socialSubjectsOf = (grade: SocialGrade) => SOCIAL_SUBJECTS.filter((subject) => SOCIAL_GRADE_DECKS[grade][subject]);

export const socialGradeDeckId = (grade: SocialGrade, subject: SocialSubject) => `${subject.toLowerCase()}-grade-${grade}`;

function deckOf(grade: SocialGrade, subject: SocialSubject) {
  const deck = SOCIAL_GRADE_DECKS[grade][subject];
  if (!deck) throw new Error(`No ${subject} deck for grade ${grade}`);
  return deck;
}

/** Deck name, e.g. "9. sınıf Tarih – anahtar kavramlar" / "History 9 – key concepts". */
export function socialGradeDeckName(grade: SocialGrade, subject: SocialSubject, lang: 'tr' | 'en') {
  return lang === 'tr' ? `${grade}. sınıf ${SOCIAL_SUBJECT_NAMES[subject].tr} – anahtar kavramlar` : `${SOCIAL_SUBJECT_NAMES[subject].en} ${grade} – key concepts`;
}

/** Card explanation: where the concept is in the MEB program. */
export function socialConceptNote(grade: SocialGrade, subject: SocialSubject, concept: GradeConcept, lang: 'tr' | 'en') {
  const deck = deckOf(grade, subject);
  const [, , unit] = concept;
  const title = deck.units[unit];
  return lang === 'tr'
    ? `MEB ${deck.program.tr} öğretim programı · ${grade}. sınıf · ${unit}. ${deck.unitWord}: ${title} (anahtar kavram).`
    : `MEB ${deck.program.en} curriculum · Grade ${grade} · ${deck.unitWord === 'ünite' ? 'Unit' : 'Theme'} ${unit}: ${title} (key concept).`;
}

export function createSocialGradeDeck(
  grade: SocialGrade,
  subject: SocialSubject,
  lang: 'tr' | 'en',
  name: string,
  now = new Date().toISOString(),
) {
  const id = socialGradeDeckId(grade, subject);
  const deck: FlashcardDeck = {
    id,
    name,
    grade: grade as FlashcardGrade,
    subject,
    topic: lang === 'tr' ? 'MEB · Anahtar kavramlar' : 'MEB · Key concepts',
    starter: false,
    createdAt: now,
  };
  const cards: Flashcard[] = deckOf(grade, subject).concepts.map((concept, index) => ({
    id: `${id}-${String(index + 1).padStart(2, '0')}`,
    deckId: id,
    front: concept[0],
    answer: concept[1],
    explanation: socialConceptNote(grade, subject, concept, lang),
  }));
  return { deck, cards };
}
