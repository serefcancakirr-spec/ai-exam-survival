function q(
  outcome: string,
  difficulty: QuizDifficulty,
  prompt: string,
  options: [string, string, string, string],
  explanation: string,
): MebSeed {
  const [prefix, grade, unit] = outcome.split('.');
  const theme = MEB10_THEMES[prefix]?.[`${grade}.${unit}`];
  if (!theme) throw new Error(`Unknown MEB outcome ${outcome}`);
  return { outcome, theme, difficulty, prompt, options, explanation };
}

