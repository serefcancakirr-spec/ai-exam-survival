export const englishGradeDeckId = (grade: GradeDeckGrade, theme: number) => `english-grade-${grade}-t${theme}`;

function themeOf(grade: GradeDeckGrade, theme: number) {
  const found = ENGLISH_GRADE_THEMES[grade].find((item) => item.theme === theme);
  if (!found) throw new Error(`No English theme ${theme} for grade ${grade}`);
  return found;
}

/** Button label, e.g. "Tema 1 · Okul Hayatı" / "Theme 1 · School Life". */
export function englishGradeThemeLabel(grade: GradeDeckGrade, theme: number, lang: 'tr' | 'en') {
  const item = themeOf(grade, theme);
  return lang === 'tr' ? `Tema ${theme} · ${item.tr}` : `Theme ${theme} · ${item.en}`;
}

/** Deck name, e.g. "9. sınıf İngilizce – Okul Hayatı" / "English 9 – School Life" (60 characters at most). */
export function englishGradeDeckName(grade: GradeDeckGrade, theme: number, lang: 'tr' | 'en') {
  const item = themeOf(grade, theme);
  return lang === 'tr' ? `${grade}. sınıf İngilizce – ${item.tr}` : `English ${grade} – ${item.en}`;
}

/** Card explanation: where the word is in the MEB program. */
export function englishGradeNote(grade: GradeDeckGrade, theme: number, lang: 'tr' | 'en') {
  const item = themeOf(grade, theme);
  return lang === 'tr'
    ? `MEB İngilizce öğretim programı · ${grade}. sınıf · Tema ${theme}: ${item.en} (hedef kelime).`
    : `MEB English Language Curriculum · Grade ${grade} · Theme ${theme}: ${item.en} (target vocabulary).`;
}

export function createEnglishGradeDeck(
  grade: GradeDeckGrade,
  theme: number,
  lang: 'tr' | 'en',
  name: string,
  now = new Date().toISOString(),
) {
  const id = englishGradeDeckId(grade, theme);
  const item = themeOf(grade, theme);
  const deck: FlashcardDeck = {
    id,
    name,
    grade: grade as FlashcardGrade,
    subject: 'English',
    topic: `MEB · ${lang === 'tr' ? item.tr : item.en}`,
    starter: false,
    createdAt: now,
  };
  const note = englishGradeNote(grade, theme, lang);
  const cards: Flashcard[] = item.words.map((word, index) => ({
    id: `${id}-${String(index + 1).padStart(2, '0')}`,
    deckId: id,
    front: `${word[0]} — “${word[2]}”`,
    answer: word[1],
    explanation: note,
  }));
  return { deck, cards };
}
