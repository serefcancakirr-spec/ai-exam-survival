/** The grade a level deck goes under when no grade filter is chosen. */
export const LEVEL_DECK_GRADE: Record<EnglishLevel, FlashcardGrade> = { A1: '9', A2: '9', B1: '10', B2: '11', C1: '12' };

export const levelDeckId = (level: EnglishLevel) => `english-level-${level.toLowerCase()}`;

/** A new level deck and its cards, named in the language in use. */
export function createLevelDeck(level: EnglishLevel, lang: 'tr' | 'en', grade: FlashcardGrade, name: string, now = new Date().toISOString()) {
  const id = levelDeckId(level);
  const deck: FlashcardDeck = {
    id,
    name,
    grade,
    subject: 'English',
    topic: lang === 'tr' ? `${level} · Kelime` : `${level} · Vocabulary`,
    starter: false,
    createdAt: now,
  };
  const cards: Flashcard[] = LEVEL_WORDS[level].map(([word, turkish, example], index) => ({
    id: `${id}-${String(index + 1).padStart(2, '0')}`,
    deckId: id,
    front: `${word} — “${example}”`,
    answer: turkish,
    explanation: '',
  }));
  return { deck, cards };
}

/** Default deck name for a level in the language in use. */
export function levelDeckName(level: EnglishLevel, lang: 'tr' | 'en') {
  return lang === 'tr' ? `İngilizce ${level} kelimeler` : `English ${level} words`;
}

